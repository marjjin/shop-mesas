using Microsoft.EntityFrameworkCore;

namespace GestionMesas.Api;

public static class InvoiceSchemaUpgrade
{
    public static void Apply(RestaurantContext db)
    {
        if (db.Database.IsSqlite()) db.Database.ExecuteSqlRaw("""
            CREATE TABLE IF NOT EXISTS "Invoices" (
                "Id" INTEGER NOT NULL CONSTRAINT "PK_Invoices" PRIMARY KEY AUTOINCREMENT,
                "SupplierId" INTEGER NOT NULL REFERENCES "Suppliers" ("Id") ON DELETE RESTRICT,
                "Reference" TEXT NOT NULL, "Note" TEXT NOT NULL, "IssueDate" TEXT NOT NULL,
                "CreatedAt" TEXT NOT NULL, "PageCount" INTEGER NOT NULL, "SizeBytes" INTEGER NOT NULL, "OriginalBytes" INTEGER NOT NULL
            );
            CREATE TABLE IF NOT EXISTS "InvoiceDocuments" (
                "InvoiceId" INTEGER NOT NULL CONSTRAINT "PK_InvoiceDocuments" PRIMARY KEY REFERENCES "Invoices" ("Id") ON DELETE CASCADE,
                "Content" BLOB NOT NULL
            );
            """);
        else if (db.Database.IsNpgsql()) db.Database.ExecuteSqlRaw("""
            CREATE TABLE IF NOT EXISTS "Invoices" (
                "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                "SupplierId" integer NOT NULL REFERENCES "Suppliers" ("Id") ON DELETE RESTRICT,
                "Reference" character varying(100) NOT NULL, "Note" character varying(1000) NOT NULL, "IssueDate" date NOT NULL,
                "CreatedAt" timestamp with time zone NOT NULL, "PageCount" integer NOT NULL, "SizeBytes" integer NOT NULL, "OriginalBytes" bigint NOT NULL
            );
            CREATE TABLE IF NOT EXISTS "InvoiceDocuments" (
                "InvoiceId" integer PRIMARY KEY REFERENCES "Invoices" ("Id") ON DELETE CASCADE,
                "Content" bytea NOT NULL
            );
            """);
        else return;
        AddDocumentColumn(db, "CloudinaryPublicId");
        AddDocumentColumn(db, "CloudinaryAssetId");
        AddDocumentColumn(db, "CloudinaryCloudName");
        if (db.Database.IsSqlite()) db.Database.ExecuteSqlRaw("""
            CREATE TABLE IF NOT EXISTS "InvoiceFileCleanups" (
                "Id" TEXT NOT NULL PRIMARY KEY, "CloudName" TEXT NOT NULL, "PublicId" TEXT NOT NULL,
                "NotBefore" TEXT NOT NULL, "Attempts" INTEGER NOT NULL
            );
            """);
        else db.Database.ExecuteSqlRaw("""
            CREATE TABLE IF NOT EXISTS "InvoiceFileCleanups" (
                "Id" text NOT NULL PRIMARY KEY, "CloudName" text NOT NULL, "PublicId" text NOT NULL,
                "NotBefore" timestamp with time zone NOT NULL, "Attempts" integer NOT NULL
            );
            """);
        db.Database.ExecuteSqlRaw("""
            CREATE INDEX IF NOT EXISTS "IX_Invoices_SupplierId_IssueDate" ON "Invoices" ("SupplierId", "IssueDate");
            CREATE INDEX IF NOT EXISTS "IX_Invoices_CreatedAt" ON "Invoices" ("CreatedAt");
            CREATE INDEX IF NOT EXISTS "IX_InvoiceDocuments_CloudinaryPublicId" ON "InvoiceDocuments" ("CloudinaryPublicId");
            CREATE INDEX IF NOT EXISTS "IX_InvoiceFileCleanups_NotBefore" ON "InvoiceFileCleanups" ("NotBefore");
            CREATE UNIQUE INDEX IF NOT EXISTS "IX_InvoiceFileCleanups_CloudName_PublicId" ON "InvoiceFileCleanups" ("CloudName", "PublicId");
            """);
    }

#pragma warning disable EF1002 // Column identifiers are constants from Apply, never request values.
    private static void AddDocumentColumn(RestaurantContext db, string column)
    {
        if (db.Database.IsNpgsql())
        {
            db.Database.ExecuteSqlRaw($"ALTER TABLE \"InvoiceDocuments\" ADD COLUMN IF NOT EXISTS \"{column}\" text NOT NULL DEFAULT ''; ");
            return;
        }
        var connection = db.Database.GetDbConnection();
        var wasClosed = connection.State != System.Data.ConnectionState.Open;
        if (wasClosed) connection.Open();
        var exists = false;
        try
        {
            using var command = connection.CreateCommand(); command.CommandText = """PRAGMA table_info("InvoiceDocuments");""";
            using var reader = command.ExecuteReader();
            while (reader.Read()) exists |= reader.GetString(1) == column;
        }
        finally { if (wasClosed) connection.Close(); }
        if (!exists) db.Database.ExecuteSqlRaw($"ALTER TABLE \"InvoiceDocuments\" ADD COLUMN \"{column}\" TEXT NOT NULL DEFAULT ''; ");
    }
#pragma warning restore EF1002
}
